"""Regenerate lib/photos/*.ts from public/images/* (the source photos).

GitHub's MCP snapshot push is text-only, so the site ships photos as data
URLs instead of binary files in public/. To update a photo: replace the
file in public/images/ (same filename), run this script, rebuild, push.
Photos are converted to WebP (quality 82) to keep the data URLs small;
the transparent logo stays PNG to preserve its alpha channel.
"""
import base64, io, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "public/images"
OUT = ROOT / "lib/photos"
NAMES = {
    "cover.jpg": ("cover", "coverPhoto"),
    "stage.jpg": ("stage", "stagePhoto"),
    "main-hall.jpg": ("mainHall", "mainHallPhoto"),
    "hall-2.jpg": ("hall2", "hall2Photo"),
    "hall-3.jpg": ("hall3", "hall3Photo"),
    "marquee.jpg": ("marquee", "marqueePhoto"),
    "interior-1.jpg": ("interior1", "interior1Photo"),
    "interior-2.jpg": ("interior2", "interior2Photo"),
    "interior-3.jpg": ("interior3", "interior3Photo"),
    "logo.png": ("logo", "logoPhoto"),
    "logo-light.jpg": ("logoLight", "logoLightPhoto"),
}
from PIL import Image
OUT.mkdir(exist_ok=True)
for src_name, (stem, var) in NAMES.items():
    src = SRC / src_name
    im = Image.open(src)
    if src.suffix == ".png":
        buf = io.BytesIO(); im.save(buf, "PNG"); mime, data = "image/png", buf.getvalue()
    else:
        if im.mode in ("RGBA", "LA", "P"):
            im = im.convert("RGB")
        buf = io.BytesIO(); im.save(buf, "WEBP", quality=82, method=6); mime, data = "image/webp", buf.getvalue()
    b64 = base64.b64encode(data).decode()
    (OUT / f"{stem}.ts").write_text(
        f'// Generated by scripts/generate-photos.py from public/images/{src_name} — do not edit by hand.\n'
        f'export const {var} = "data:{mime};base64,{b64}";\n')
    print(f"{src_name}: {src.stat().st_size//1024}KB -> {len(data)//1024}KB {mime} ({stem}.ts)")
